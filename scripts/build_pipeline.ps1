[CmdletBinding()]
param(
    [string]$ProjectRoot = 'C:\PRJ381',
    [ValidateSet('All', 'Windows', 'Android', 'Quest', 'Validate')]
    [string]$Target = 'All'
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$Root = [IO.Path]::GetFullPath($ProjectRoot)
$Project = Join-Path $Root 'PRJ381.uproject'
$Uat = 'C:\Program Files\Epic Games\UE_5.8\Engine\Build\BatchFiles\RunUAT.bat'
$PackagingSection = '[/Script/UnrealEd.ProjectPackagingSettings]'
$AndroidSection = '[/Script/AndroidRuntimeSettings.AndroidRuntimeSettings]'
$PadSection = '[/Script/GooglePADEditor.GooglePADRuntimeSettings]'
$RunId = [Guid]::NewGuid().ToString('N')
$GeneratedHeader = '// Generated by PRJ381 build_pipeline.ps1; do not edit.'
$PackLimitBytes = [long]1400000000
$ManagedPackPrefix = 'prj381_chunk'
$SourcePackRoot = Join-Path $Root 'Build\Android\gradle\assetpacks\on-demand'
$IntermediateRoot = Join-Path $Root 'Intermediate\Android'

function Invoke-Uat {
    param(
        [string[]]$UatArguments,
        [string]$StepName = 'UAT'
    )
    $LogDir = Join-Path $Root 'Saved\Logs'
    New-Item -ItemType Directory -Path $LogDir -Force | Out-Null
    $StepLog = Join-Path $LogDir ("UAT_${StepName}_${RunId}.log")
    $EffectiveArguments = @($UatArguments) + @("-log=$StepLog")
    $UatEngineLogDir = Join-Path $env:APPDATA 'Unreal Engine\AutomationTool\Logs\C+Program+Files+Epic+Games+UE_5.8'
    $StepStart = (Get-Date).AddSeconds(-2)
    Write-Host ('RunUAT [' + $StepName + ']: ' + ($EffectiveArguments -join ' '))
    try {
        & $Uat @EffectiveArguments
        $ExitCode = $LASTEXITCODE
    } finally {
        if (Test-Path -LiteralPath $UatEngineLogDir) {
            Get-ChildItem -LiteralPath $UatEngineLogDir -Filter 'Cook-*.txt' -File -ErrorAction SilentlyContinue |
                Where-Object { $_.LastWriteTime -ge $StepStart } |
                ForEach-Object {
                    Copy-Item -LiteralPath $_.FullName -Destination (Join-Path $LogDir ("UAT_${StepName}_${RunId}_" + $_.Name)) -Force
                }
            $DefaultLog = Join-Path $UatEngineLogDir 'Log.txt'
            if ((Test-Path -LiteralPath $DefaultLog -PathType Leaf) -and !(Test-Path -LiteralPath $StepLog -PathType Leaf)) {
                Copy-Item -LiteralPath $DefaultLog -Destination $StepLog -Force
            }
        }
    }
    if ($ExitCode -ne 0) {
        throw "RunUAT [$StepName] failed with exit code $ExitCode (see $StepLog). No subsequent build step will run."
    }
}

function Get-ConfigArgument {
    param([string]$Type, [string]$Section, [string]$Key, [string]$Value)
    return ('-ini:{0}:{1}:{2}={3}' -f $Type, $Section, $Key, $Value)
}

function Get-ContainerFiles {
    param([string]$Directory)
    $result = @()
    foreach ($extension in @('*.pak', '*.utoc', '*.ucas', '*.sig')) {
        $result += @(Get-ChildItem -LiteralPath $Directory -Filter $extension -File -Recurse)
    }
    return $result
}

function Remove-ManagedPacks {
    # Only remove our marked generated modules, never source assets or whole caches.
    $directories = @()
    if (Test-Path -LiteralPath $SourcePackRoot) {
        $directories += @(Get-ChildItem -LiteralPath $SourcePackRoot -Directory -Filter ($ManagedPackPrefix + '*'))
    }
    if (Test-Path -LiteralPath $IntermediateRoot) {
        $directories += @(Get-ChildItem -LiteralPath $IntermediateRoot -Directory -Filter ($ManagedPackPrefix + '*') -Recurse |
            Where-Object { $_.FullName -match '[\\/]gradle[\\/]assetpacks[\\/]on-demand[\\/]' })
    }
    foreach ($directory in $directories) {
        $gradle = Join-Path $directory.FullName 'build.gradle'
        if (!(Test-Path -LiteralPath $gradle) -or
            (Get-Content -LiteralPath $gradle -TotalCount 1) -ne $GeneratedHeader) {
            throw "Refusing to overwrite or delete an unmarked asset pack: $($directory.FullName)"
        }
        Remove-Item -LiteralPath $directory.FullName -Recurse -Force
    }
}

function Build-Windows {
    Write-Host '=== Windows Desktop / Development ==='
    # Clear the previous archive and staged build so a no-chunk desktop build
    # cannot pick up leftover pakchunk*.pak containers from a chunked build.
    foreach ($Stale in @((Join-Path $Root 'Builds\Windows'), (Join-Path $Root 'Saved\StagedBuilds\Windows'))) {
        if (Test-Path -LiteralPath $Stale) { Remove-Item -LiteralPath $Stale -Recurse -Force }
    }
    Invoke-Uat -StepName 'Windows_BuildCookRun' -UatArguments @(
        'BuildCookRun', "-project=$Project", '-nop4', '-unattended', '-utf8output',
        '-platform=Win64', '-clientconfig=Development', '-serverconfig=Development',
        '-build', '-cook', '-allmaps', '-stage', '-pak', '-package', '-archive',
        ('-archivedirectory=' + (Join-Path $Root 'Builds\Windows')),
        (Get-ConfigArgument Game $PackagingSection bGenerateChunks False),
        (Get-ConfigArgument Game $PackagingSection bGenerateNoChunks True)
    )
}

function Build-AndroidPad {
    Write-Host '=== Android Mobile / Development / ASTC / GooglePAD ==='
    # UEDeployAndroid resolves its intermediate OBB from this standard location.
    # Clear ONLY generated staging artifacts; preserve source files, logs, saves and caches.
    $StageBase = Join-Path $Root 'Saved\StagedBuilds\Android_ASTC'
    if (Test-Path -LiteralPath $StageBase) { Remove-Item -LiteralPath $StageBase -Recurse -Force }
    Get-ChildItem -LiteralPath (Split-Path -Parent $StageBase) -Filter 'Android_ASTC*.obb' -File -ErrorAction SilentlyContinue | Remove-Item -Force
    $Archive = Join-Path $Root ('Builds\Android\' + $RunId)
    $common = @(
        'BuildCookRun', "-project=$Project", '-nop4', '-unattended', '-utf8output',
        '-platform=Android', '-cookflavor=ASTC',
        '-clientconfig=Development', '-serverconfig=Development',
        '-pak', '-iostore', '-manifests',
        (Get-ConfigArgument Engine $AndroidSection bEnableBundle True),
        (Get-ConfigArgument Engine $AndroidSection bEnableUniversalAPK False),
        (Get-ConfigArgument Engine $AndroidSection bPackageDataInsideApk False),
        (Get-ConfigArgument Engine $AndroidSection bAllowPatchOBBFile False),
        (Get-ConfigArgument Engine $AndroidSection bPackageForMetaQuest False),
        (Get-ConfigArgument Engine $PadSection bEnablePlugin True),
        (Get-ConfigArgument Engine $PadSection bOnlyDistribution False),
        (Get-ConfigArgument Engine $PadSection bOnlyShipping False),
        (Get-ConfigArgument Game $PackagingSection ForDistribution False),
        (Get-ConfigArgument Game $PackagingSection bGenerateChunks True),
        (Get-ConfigArgument Game $PackagingSection bGenerateNoChunks False)
    )
    Remove-ManagedPacks
    try {
        # Phase A: create complete chunk containers without Android packaging.
        $PhaseAStart = (Get-Date).AddSeconds(-2)
        Invoke-Uat -StepName 'Android_PhaseA_CookStage' -UatArguments ($common + @('-build', '-cook', '-allmaps', '-stage', '-skippackage'))
        $CookMeta = Join-Path $Root 'Saved\Cooked\Android_ASTC\PRJ381\Metadata\CookMetadata.ucookmeta'
        if (!(Test-Path -LiteralPath $CookMeta -PathType Leaf) -or (Get-Item -LiteralPath $CookMeta).LastWriteTime -lt $PhaseAStart) {
            throw "Phase A did not produce fresh cook metadata ($CookMeta is missing or older than $PhaseAStart). Refusing to run Phase B."
        }
        if (!(Test-Path -LiteralPath $StageBase)) { throw "Stage directory was not created: $StageBase" }
        $containers = @(Get-ContainerFiles $StageBase)
        $staleContainers = @($containers | Where-Object { $_.LastWriteTime -lt $PhaseAStart })
        if ($staleContainers.Count -gt 0) {
            throw "Phase A staged containers older than ${PhaseAStart}: $(($staleContainers | ForEach-Object { $_.Name }) -join ', '). Refusing to run Phase B."
        }
        $groups = @{}
        $startup = @()
        foreach ($file in $containers) {
            if ($file.Name -match '^pakchunk(?<id>[0-9]+)(?:optional)?(?:[-_.])') {
                $id = [int]$Matches['id']
                if ($id -eq 0) { $startup += $file; continue }
                if (!$groups.ContainsKey($id)) { $groups[$id] = @() }
                $groups[$id] += $file
            } else {
                $startup += $file
            }
        }
        if ($groups.Count -eq 0) {
            Write-Warning 'No nonzero asset chunks were produced. Assign campus content to nonzero chunk IDs in Asset Manager/Primary Asset Labels, keeping startup dependencies in chunk 0. Generate Chunks alone does not assign content. Packaging stopped before creating an oversized OBB.'
        }
        if (!(@($startup | Where-Object { $_.Extension -eq '.utoc' }).Count)) {
            throw 'The staged IOStore startup container is missing. Refusing to package an incomplete startup build.'
        }
        $startupBytes = [long]($startup | Measure-Object -Property Length -Sum).Sum
        if ($startupBytes -gt $PackLimitBytes) {
            throw "Startup containers total $startupBytes bytes. Move more non-startup content out of chunk 0; the conservative install-time budget is $PackLimitBytes bytes."
        }
        $filters = @()
        $expectedPacks = @()
        foreach ($id in @($groups.Keys | Sort-Object)) {
            $files = @($groups[$id])
            if (!(@($files | Where-Object { $_.Extension -eq '.utoc' }).Count) -or
                !(@($files | Where-Object { $_.Extension -eq '.ucas' }).Count)) {
                throw "Chunk $id is missing IOStore .utoc/.ucas companions."
            }
            $bytes = [long]($files | Measure-Object -Property Length -Sum).Sum
            if ($bytes -gt $PackLimitBytes) {
                throw "Chunk $id totals $bytes bytes; split it into more chunk IDs. Splitting one chunk into multiple files does not reduce its asset-pack total."
            }
            $name = $ManagedPackPrefix + $id
            $module = Join-Path $SourcePackRoot $name
            $assets = Join-Path $module 'src\main\assets'
            New-Item -ItemType Directory -Path $assets -Force | Out-Null
            $gradle = @(
                $GeneratedHeader,
                "apply plugin: 'com.android.asset-pack'",
                'assetPack {',
                "    packName = '$name'",
                '    dynamicDelivery {',
                "        deliveryType = 'on-demand'",
                '    }',
                '}'
            ) -join "`r`n"
            [IO.File]::WriteAllText((Join-Path $module 'build.gradle'), $gradle + "`r`n", (New-Object Text.UTF8Encoding($false)))
            $seenNames = @{}
            foreach ($file in $files) {
                if ($seenNames.ContainsKey($file.Name)) { throw "Duplicate container filename in chunk ${id}: $($file.Name)" }
                $seenNames[$file.Name] = $true
                Copy-Item -LiteralPath $file.FullName -Destination (Join-Path $assets $file.Name)
                # Exact staged filenames, not broad prefixes that accidentally match chunk 10.
                $filters += Get-ConfigArgument Engine $AndroidSection '+ObbFilters' ('-*' + $file.Name)
            }
            $expectedPacks += $name
            Write-Host "Prepared $name ($bytes bytes), including all staged container companions."
        }
        # Phase B: package the SAME stage with bulk chunks excluded from the intermediate OBB.
        Invoke-Uat -StepName 'Android_PhaseB_Package' -UatArguments ($common + $filters + @(
            '-skipcook', '-skipstage', '-package', '-archive', "-archivedirectory=$Archive"
        ))
        $bundles = @(Get-ChildItem -LiteralPath $Archive -Filter '*.aab' -File -Recurse)
        if ($bundles.Count -ne 1) { throw "Expected one AAB in $Archive, found $($bundles.Count)." }
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $zip = [IO.Compression.ZipFile]::OpenRead($bundles[0].FullName)
        try {
            foreach ($name in $expectedPacks) {
                if ($null -eq $zip.GetEntry("$name/manifest/AndroidManifest.xml")) {
                    throw "AAB is missing expected asset-pack module $name."
                }
                foreach ($file in @($groups[[int]($name.Substring($ManagedPackPrefix.Length))])) {
                    $entry = $zip.GetEntry("$name/assets/$($file.Name)")
                    if ($null -eq $entry -or $entry.Length -ne $file.Length) {
                        throw "AAB asset-pack content is missing or truncated: $name/$($file.Name)"
                    }
                }
            }
            $obb = $zip.GetEntry('obbassets/assets/main.obb.png')
            if ($null -eq $obb) { throw 'AAB is missing the stock GooglePAD install-time startup pack.' }
            if ($obb.Length -gt $PackLimitBytes) {
                throw "Startup OBB is $($obb.Length) bytes, exceeding the conservative asset-pack budget."
            }
        } finally { $zip.Dispose() }
        # Publish a fresh, deterministic pointer only after artifact validation succeeds.
        $receipt = [ordered]@{
            aab = $bundles[0].FullName
            configuration = 'Development'
            cookFlavor = 'ASTC'
            assetPacks = $expectedPacks
            runtimeDeliveryVerified = $false
            deploymentPerformed = $false
        }
        $receipt | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $Root 'Builds\Android\latest-pad.json') -Encoding UTF8
        Write-Host ('Validated AAB package structure: ' + $bundles[0].FullName)
        Write-Warning 'On-demand delivery and IOStore mounting must be implemented and tested in the application. Package validation is not runtime verification.'
    } finally {
        Remove-ManagedPacks
    }
}

function Build-Quest {
    Write-Host '=== Meta Quest / Development / ASTC / APK ==='
    # Quest is NOT a Google Play PAD target. Do not inherit the mobile bundle settings.
    Invoke-Uat -StepName 'Quest_BuildCookRun' -UatArguments @(
        'BuildCookRun', "-project=$Project", '-nop4', '-unattended', '-utf8output',
        '-platform=Android', '-cookflavor=ASTC',
        '-clientconfig=Development', '-serverconfig=Development',
        '-build', '-cook', '-allmaps', '-stage', '-pak', '-package', '-archive',
        ('-archivedirectory=' + (Join-Path $Root 'Builds\Quest3')),
        (Get-ConfigArgument Engine $AndroidSection bEnableBundle False),
        (Get-ConfigArgument Engine $AndroidSection bPackageForMetaQuest True),
        (Get-ConfigArgument Engine $PadSection bEnablePlugin False),
        (Get-ConfigArgument Game $PackagingSection bGenerateChunks False)
    )
}

try {
    if (!(Test-Path -LiteralPath $Project -PathType Leaf)) { throw "Project not found: $Project" }
    if (!(Test-Path -LiteralPath $Uat -PathType Leaf)) { throw "RunUAT not found: $Uat" }
    if ($Target -eq 'Validate') {
        Write-Host 'CI entry point, project path, and UE 5.8 RunUAT path validated. No build, cook, staging, packaging, or deployment was run.'
        exit 0
    }
    Push-Location $Root
    try {
        switch ($Target) {
            'All' { Build-Windows; Build-AndroidPad; Build-Quest }
            'Windows' { Build-Windows }
            'Android' { Build-AndroidPad }
            'Quest' { Build-Quest }
        }
    } finally { Pop-Location }
    Write-Host 'Requested CI build stages completed.'
    exit 0
} catch {
    [Console]::Error.WriteLine('CI FAILED: ' + $_.Exception.Message)
    exit 1
}


